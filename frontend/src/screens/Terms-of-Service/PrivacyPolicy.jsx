const PrivacyPolicy = ({ navigation }) => {
  const { width } = useWindowDimensions();
  const normalize = useMemo(() => getNormalize(width), [width]);
  const styles = useMemo(() => createServiceStyles(normalize), [normalize]);

  return (
    <SafeAreaView style={styles.container} edges={['top']}>
      <SubHeader title="개인정보 처리방침" onBack={() => navigation.goBack()} />
      <ScrollView
        style={styles.scroll}
        contentContainerStyle={styles.scrollContent}
        showsVerticalScrollIndicator={false}
      >
        {POLICY_LINES.map((line, idx) => {
          if (line === '---') return <View key={`d-${idx}`} style={styles.divider} />;
          if (line.startsWith('## ')) {
            return (
              <Text key={`c-${idx}`} style={styles.chapterTitle}>
                {line.replace('## ', '')}
              </Text>
            );
          }
          if (line.startsWith('### ')) {
            return (
              <Text key={`s-${idx}`} style={styles.sectionTitle}>
                {line.replace('### ', '')}
              </Text>
            );
          }
          if (line.startsWith('- ')) {
            return (
              <Text key={`b-${idx}`} style={styles.bullet}>
                {'• '}
                {line.replace('- ', '')}
              </Text>
            );
          }
          return (
            <Text key={`p-${idx}`} style={styles.para}>
              {line}
            </Text>
          );
        })}
      </ScrollView>
    </SafeAreaView>
  );
};

export default PrivacyPolicy;
