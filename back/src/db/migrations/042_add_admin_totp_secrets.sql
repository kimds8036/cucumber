-- 관리자 Google OTP (TOTP) 2FA

CREATE TABLE IF NOT EXISTS admin_totp_secrets (
  user_id INT NOT NULL PRIMARY KEY COMMENT '관리자 users.id',
  secret_enc TEXT NOT NULL COMMENT 'AES-256-GCM 암호화된 TOTP secret',
  confirmed_at TIMESTAMP NULL DEFAULT NULL COMMENT 'OTP 등록 완료 시각 (NULL=QR만 발급·미확인)',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='관리자 TOTP 2FA secret';
